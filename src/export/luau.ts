// Command Bar script export: an alternative to the .rbxmx file that builds the
// KeyframeSequence (and a rig, if you haven't selected one) directly in Studio.

import { qId } from "../math/math3d";
import { HIP_HEIGHT, JOINTS, PARTS, childrenOf, jointOffsets, type JointPart, type PartName } from "../rig/r15";
import { sampleAnim, type KeyedAnim } from "../solve/keyframes";
import { EASING_ENUM, PRIORITY_ENUM, type Settings } from "../solve/settings";

const f = (x: number) => {
  const r = Math.round(x * 1e5) / 1e5;
  return Object.is(r, -0) ? "0" : String(r);
};

function encodeAnim(anim: KeyedAnim, s: Settings): string {
  const times = new Set<number>();
  for (const j of Object.keys(anim.joints) as JointPart[]) anim.joints[j].t.forEach((t) => times.add(t));
  const lines: string[] = [];
  for (const t of [...times].sort((a, b) => a - b)) {
    const sampled = s.keyAllJoints ? sampleAnim(anim, t) : null;
    const entries: string[] = [];
    const visit = (part: PartName, parent: string): boolean => {
      let q = qId(), p: [number, number, number] = [0, 0, 0], keyed = false;
      if (part !== "HumanoidRootPart") {
        const k = anim.joints[part as JointPart];
        const i = k.t.indexOf(t);
        if (i >= 0) {
          q = k.q[i];
          if (k.p) p = k.p[i];
          keyed = true;
        } else if (sampled) {
          q = sampled.rot[part as JointPart];
          if (part === "LowerTorso") p = sampled.rootPos;
          keyed = true;
        }
      }
      const mine = entries.length;
      entries.push("");
      let any = keyed;
      for (const c of childrenOf(part)) any = visit(c, part) || any;
      if (!any) {
        entries.splice(mine);
        return false;
      }
      entries[mine] = [part, parent, keyed ? 1 : 0, ...p.map(f), ...q.map(f)].join(",");
      return true;
    };
    visit("HumanoidRootPart", "");
    lines.push(`${f(t)}|${entries.join("|")}`);
  }
  return lines.join("\n");
}

export function luauScript(anim: KeyedAnim, s: Settings): string {
  const parts = (Object.keys(PARTS) as PartName[])
    .map((n) => {
      const d = PARTS[n];
      return `\t{"${n}", Vector3.new(${d.size.map(f)}), Vector3.new(${d.pos.map(f)}), Color3.fromRGB(${d.color})},`;
    })
    .join("\n");
  const joints = JOINTS.map((j) => {
    const { c0, c1 } = jointOffsets(j);
    return `\t{"${j.motor}", "${j.part0}", "${j.part1}", "${j.attachment}", Vector3.new(${c0.map(f)}), Vector3.new(${c1.map(f)})},`;
  }).join("\n");
  const name = (s.name || "Animation").replace(/[^\w ]/g, "");
  const easing = anim.constant ? "Constant" : s.easing;

  return `-- Generated by Ronimate (video → R15 animation)
-- HOW TO USE: In Roblox Studio open View ▸ Command Bar, paste this whole script and press Enter.
--   • If an R15 rig/avatar Model is selected, the animation is saved into its AnimSaves.
--   • Otherwise a new R15 rig is created in Workspace.
-- Then open Avatar ▸ Animation Editor, click the rig, and choose "${name}" from the Load menu.

local NAME = "${name}"
local LOOP = ${s.loop}
local PRIORITY = Enum.AnimationPriority.${s.priority} -- (${PRIORITY_ENUM[s.priority]})
local EASING = Enum.PoseEasingStyle.${easing} -- (${EASING_ENUM[easing]})

local PARTS = {
${parts}
}
local JOINTS = {
${joints}
}

local DATA = [==[
${encodeAnim(anim, s)}
]==]

local function buildRig()
	local model = Instance.new("Model")
	model.Name = NAME .. "Rig"
	local made = {}
	for _, p in ipairs(PARTS) do
		local part = Instance.new("Part")
		part.Name = p[1]
		part.Size = p[2]
		part.CFrame = CFrame.new(p[3])
		part.Color = p[4]
		part.Anchored = p[1] == "HumanoidRootPart"
		part.CanCollide = false
		part.TopSurface = Enum.SurfaceType.Smooth
		part.BottomSurface = Enum.SurfaceType.Smooth
		if p[1] == "HumanoidRootPart" then part.Transparency = 1 end
		if p[1] == "Head" then
			local mesh = Instance.new("SpecialMesh")
			mesh.MeshType = Enum.MeshType.Head
			mesh.Scale = Vector3.new(1.25, 1.25, 1.25)
			mesh.Parent = part
			local face = Instance.new("Decal")
			face.Name = "face"
			face.Texture = "rbxasset://textures/face.png"
			face.Parent = part
		end
		part.Parent = model
		made[p[1]] = part
	end
	for _, j in ipairs(JOINTS) do
		local a0 = Instance.new("Attachment")
		a0.Name = j[4]
		a0.Position = j[5]
		a0.Parent = made[j[2]]
		local a1 = Instance.new("Attachment")
		a1.Name = j[4]
		a1.Position = j[6]
		a1.Parent = made[j[3]]
		local m = Instance.new("Motor6D")
		m.Name = j[1]
		m.Part0 = made[j[2]]
		m.Part1 = made[j[3]]
		m.C0 = CFrame.new(j[5])
		m.C1 = CFrame.new(j[6])
		m.Parent = made[j[3]]
	end
	local hum = Instance.new("Humanoid")
	hum.RigType = Enum.HumanoidRigType.R15
	hum.HipHeight = ${HIP_HEIGHT}
	hum.Parent = model
	Instance.new("Animator").Parent = hum
	model.PrimaryPart = made.HumanoidRootPart
	model.Parent = workspace
	return model
end

local function buildSequence()
	local seq = Instance.new("KeyframeSequence")
	seq.Name = NAME
	seq.Loop = LOOP
	seq.Priority = PRIORITY
	pcall(function() seq.AuthoredHipHeight = ${HIP_HEIGHT} end)
	for line in DATA:gmatch("[^\\n]+") do
		local fields = string.split(line, "|")
		local kf = Instance.new("Keyframe")
		kf.Time = tonumber(fields[1])
		local poses = {}
		for i = 2, #fields do
			local v = string.split(fields[i], ",")
			local pose = Instance.new("Pose")
			pose.Name = v[1]
			pose.Weight = tonumber(v[3])
			pose.CFrame = CFrame.new(tonumber(v[4]), tonumber(v[5]), tonumber(v[6]),
				tonumber(v[7]), tonumber(v[8]), tonumber(v[9]), tonumber(v[10]))
			pose.EasingStyle = EASING
			pose.EasingDirection = Enum.PoseEasingDirection.In
			pose.Parent = poses[v[2]] or kf
			poses[v[1]] = pose
		end
		kf.Parent = seq
	end
	return seq
end

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local Selection = game:GetService("Selection")
local recording = ChangeHistoryService:TryBeginRecording("Ronimate import")

local rig
for _, obj in ipairs(Selection:Get()) do
	local model = obj:IsA("Model") and obj or obj:FindFirstAncestorOfClass("Model")
	if model and model:FindFirstChildOfClass("Humanoid") then rig = model break end
end
rig = rig or buildRig()

local saves = rig:FindFirstChild("AnimSaves")
if not saves then
	saves = Instance.new("ObjectValue")
	saves.Name = "AnimSaves"
	saves.Parent = rig
end
local old = saves:FindFirstChild(NAME)
if old then old:Destroy() end
buildSequence().Parent = saves
Selection:Set({ rig })
if recording then ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit) end
print(("[Ronimate] Added animation %q to %s.AnimSaves — open the Animation Editor and Load it."):format(NAME, rig:GetFullName()))
`;
}
